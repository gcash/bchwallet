// AuthenticationTokenKey is the key used in the context to authenticate clients.
// If this is set to anything other than "" in the config, then the server expects
// the client to set a key value in the context metadata to 'AuthenticationToken: cfg.AuthToken'
const AuthenticationTokenKey = "AuthenticationToken"

// openRPCKeyPair creates or loads the RPC TLS keypair specified by the
// application config.  This function respects the cfg.OneTimeTLSKey setting.
func openRPCKeyPair() (tls.Certificate, error) {
	// Check for existence of the TLS key file.  If one time TLS keys are
	// enabled but a key already exists, this function should error since
	// it's possible that a persistent certificate was copied to a remote
	// machine.  Otherwise, generate a new keypair when the key is missing.
	// When generating new persistent keys, overwriting an existing cert is
	// acceptable if the previous execution used a one time TLS key.
	// Otherwise, both the cert and key should be read from disk.  If the
	// cert is missing, the read error will occur in LoadX509KeyPair.
	_, e := os.Stat(cfg.RPCKey.Value)
	keyExists := !os.IsNotExist(e)
	switch {
	case cfg.OneTimeTLSKey && keyExists:
		err := fmt.Errorf("one time TLS keys are enabled, but TLS key "+
			"`%s` already exists", cfg.RPCKey.Value)
		return tls.Certificate{}, err
	case cfg.OneTimeTLSKey:
		return generateRPCKeyPair(false)
	case !keyExists:
		return generateRPCKeyPair(true)
	default:
		return tls.LoadX509KeyPair(cfg.RPCCert.Value, cfg.RPCKey.Value)
	}
}

// generateRPCKeyPair generates a new RPC TLS keypair and writes the cert and
// possibly also the key in PEM format to the paths specified by the config.  If
// successful, the new keypair is returned.
func generateRPCKeyPair(writeKey bool) (tls.Certificate, error) {
	log.Infof("Generating TLS certificates...")

	// Create directories for cert and key files if they do not yet exist.
	certDir, _ := filepath.Split(cfg.RPCCert.Value)
	keyDir, _ := filepath.Split(cfg.RPCKey.Value)
	err := os.MkdirAll(certDir, 0700)
	if err != nil {
		return tls.Certificate{}, err
	}
	err = os.MkdirAll(keyDir, 0700)
	if err != nil {
		return tls.Certificate{}, err
	}

	// Generate cert pair.
	org := "bchwallet autogenerated cert"
	validUntil := time.Now().Add(time.Hour * 24 * 365 * 10)
	cert, key, err := bchutil.NewTLSCertPair(org, validUntil, nil)
	if err != nil {
		return tls.Certificate{}, err
	}
	keyPair, err := tls.X509KeyPair(cert, key)
	if err != nil {
		return tls.Certificate{}, err
	}

	// Write cert and (potentially) the key files.
	err = os.WriteFile(cfg.RPCCert.Value, cert, 0600)
	if err != nil {
		return tls.Certificate{}, err
	}
	if writeKey {
		err = os.WriteFile(cfg.RPCKey.Value, key, 0600)
		if err != nil {
			rmErr := os.Remove(cfg.RPCCert.Value)
			if rmErr != nil {
				log.Warnf("Cannot remove written certificates: %v",
					rmErr)
			}
			return tls.Certificate{}, err
		}
	}

	log.Info("Done generating TLS certificates")
	return keyPair, nil
}

func startRPCServers(walletLoader *wallet.Loader) (*grpc.Server, *legacyrpc.Server, error) {
	var (
		server       *grpc.Server
		legacyServer *legacyrpc.Server
		keyPair      tls.Certificate
		err          error
	)

	// Load or generate the TLS key pair only when a server uses TLS: the
	// gRPC server unless its TLS is disabled, and the legacy RPC server,
	// which always does.  Generating it reads the addresses of the network
	// interfaces, which Android does not let apps targeting API 30 or newer
	// do, so an app that embeds the wallet with --noservertls must not.
	grpcTLS := len(cfg.ExperimentalRPCListeners) != 0 && !cfg.DisableServerTLS
	legacyRPC := cfg.Username != "" && cfg.Password != "" &&
		len(cfg.LegacyRPCListeners) != 0
	if grpcTLS || legacyRPC {
		keyPair, err = openRPCKeyPair()
		if err != nil {
			return nil, nil, err
		}
	}

	// Change the standard net.Listen function to the tls one.
	tlsConfig := &tls.Config{
		Certificates: []tls.Certificate{keyPair},
		MinVersion:   tls.VersionTLS12,
		NextProtos:   []string{"h2"}, // HTTP/2 over TLS
	}
	legacyListen := func(net string, laddr string) (net.Listener, error) {
		return tls.Listen(net, laddr, tlsConfig)
	}

	// Create the listeners of both servers before starting either, so that
	// nothing has started when one fails: no interrupt handler would stop
	// it, and it would outlive the run in a process that runs the wallet
	// again.
	var grpcListeners, legacyListeners []net.Listener
	if len(cfg.ExperimentalRPCListeners) != 0 {
		grpcListeners = makeListeners(cfg.ExperimentalRPCListeners, net.Listen)
		if len(grpcListeners) == 0 {
			err := errors.New("failed to create listeners for RPC server")
			return nil, nil, err
		}
	}
	if cfg.Username == "" || cfg.Password == "" {
		log.Info("Legacy RPC server disabled (requires username and password)")
	} else if len(cfg.LegacyRPCListeners) != 0 {
		legacyListeners = makeListeners(cfg.LegacyRPCListeners, legacyListen)
		if len(legacyListeners) == 0 {
			closeListeners(grpcListeners)
			err := errors.New("failed to create listeners for legacy RPC server")
			return nil, nil, err
		}
	}

	if len(grpcListeners) != 0 {
		// Stop waits for the handlers to return, so that the shutdown
		// can tell when no call uses the wallet or the services any
		// more.
		opts := []grpc.ServerOption{grpc.StreamInterceptor(interceptStreaming), grpc.UnaryInterceptor(interceptUnary),
			grpc.WaitForHandlers(true)}
		if !cfg.DisableServerTLS {
			creds := credentials.NewServerTLSFromCert(&keyPair)
			opts = append(opts, grpc.Creds(creds))
		}
		server = grpc.NewServer(opts...)
		rpcserver.RegisterServices(server)
		for _, lis := range grpcListeners {
			lis := lis
			go func() {
				log.Infof("Experimental RPC server listening on %s",
					lis.Addr())
				err := server.Serve(lis)
				log.Tracef("Finished serving expimental RPC: %v",
					err)
			}()
		}
	}

	if len(legacyListeners) != 0 {
		opts := legacyrpc.Options{
			Username:            cfg.Username,
			Password:            cfg.Password,
			MaxPOSTClients:      cfg.LegacyRPCMaxClients,
			MaxWebsocketClients: cfg.LegacyRPCMaxWebsockets,
		}
		legacyServer = legacyrpc.NewServer(&opts, walletLoader, legacyListeners)
	}

	// Error when neither the GRPC nor legacy RPC servers can be started.
	if server == nil && legacyServer == nil {
		return nil, nil, errors.New("no suitable RPC services can be started")
	}

	return server, legacyServer, nil
}

// closeListeners closes listeners that no server serves.
func closeListeners(listeners []net.Listener) {
	for _, l := range listeners {
		if err := l.Close(); err != nil {
			log.Warnf("Cannot close listener %s: %v", l.Addr(), err)
		}
	}
}

// serviceName returns the package.service segment from the full gRPC method
// name `/package.service/method`.
func serviceName(method string) string {
	// Slice off first /
	method = method[1:]
	// Keep everything before the next /
	return method[:strings.IndexRune(method, '/')]
}

// recoverHandler, deferred by an interceptor, turns a panic in a call to method
// into an Internal error, so that a bug in one call does not crash the process,
// which is an app's when the wallet is embedded.
func recoverHandler(method string, err *error) {
	if r := recover(); r != nil {
		grpcLog.Errorf("Method %s panicked: %v\n%s", method, r, debug.Stack())
		*err = status.Errorf(codes.Internal, "%s failed with an internal error",
			method)
	}
}

func interceptStreaming(srv interface{}, ss grpc.ServerStream, info *grpc.StreamServerInfo, handler grpc.StreamHandler) (err error) {
	defer recoverHandler(info.FullMethod, &err)

	p, ok := peer.FromContext(ss.Context())
	if ok {
		grpcLog.Infof("Streaming method %s invoked by %s", info.FullMethod,
			p.Addr.String())
	}

	err = validateAuthenticationToken(ss.Context())
	if err != nil {
		return err
	}

	err = rpcserver.ServiceReadyFor(serviceName(info.FullMethod), srv)
	if err != nil {
		return err
	}
	err = handler(srv, ss)
	if err != nil && ok {
		grpcLog.Errorf("Streaming method %s invoked by %s errored: %v",
			info.FullMethod, p.Addr.String(), err)
	}
	return err
}

func interceptUnary(ctx context.Context, req interface{}, info *grpc.UnaryServerInfo, handler grpc.UnaryHandler) (resp interface{}, err error) {
	defer recoverHandler(info.FullMethod, &err)

	p, ok := peer.FromContext(ctx)
	if ok {
		grpcLog.Infof("Unary method %s invoked by %s", info.FullMethod,
			p.Addr.String())
	}

	err = validateAuthenticationToken(ctx)
	if err != nil {
		return nil, err
	}

	err = rpcserver.ServiceReadyFor(serviceName(info.FullMethod), info.Server)
	if err != nil {
		return nil, err
	}
	resp, err = handler(ctx, req)
	if err != nil && ok {
		grpcLog.Errorf("Unary method %s invoked by %s errored: %v",
			info.FullMethod, p.Addr.String(), err)
	}
	return resp, err
}

func validateAuthenticationToken(ctx context.Context) error {
	if cfg.AuthToken == "" {
		return nil
	}
	var token string
	if md, ok := metadata.FromIncomingContext(ctx); ok {
		if tokens := md.Get(AuthenticationTokenKey); len(tokens) > 0 {
			token = tokens[0]
		}
	}
	// Compare in constant time, so that how long a wrong token takes to
	// refuse does not tell how much of it is right.
	if subtle.ConstantTimeCompare([]byte(token), []byte(cfg.AuthToken)) != 1 {
		return status.Error(codes.Unauthenticated, "invalid authentication token")
	}
	return nil
}

type listenFunc func(net string, laddr string) (net.Listener, error)

// makeListeners splits the normalized listen addresses into IPv4 and IPv6
// addresses and creates new net.Listeners for each with the passed listen func.
// Invalid addresses are logged and skipped.
func makeListeners(normalizedListenAddrs []string, listen listenFunc) []net.Listener {
	ipv4Addrs := make([]string, 0, len(normalizedListenAddrs)*2)
	ipv6Addrs := make([]string, 0, len(normalizedListenAddrs)*2)
	for _, addr := range normalizedListenAddrs {
		host, _, err := net.SplitHostPort(addr)
		if err != nil {
			// Shouldn't happen due to already being normalized.
			log.Errorf("`%s` is not a normalized "+
				"listener address", addr)
			continue
		}

		// Empty host or host of * on plan9 is both IPv4 and IPv6.
		if host == "" || (host == "*" && runtime.GOOS == "plan9") {
			ipv4Addrs = append(ipv4Addrs, addr)
			ipv6Addrs = append(ipv6Addrs, addr)
			continue
		}

		// Remove the IPv6 zone from the host, if present.  The zone
		// prevents ParseIP from correctly parsing the IP address.
		// ResolveIPAddr is intentionally not used here due to the
		// possibility of leaking a DNS query over Tor if the host is a
		// hostname and not an IP address.
		zoneIndex := strings.Index(host, "%")
		if zoneIndex != -1 {
			host = host[:zoneIndex]
		}

		ip := net.ParseIP(host)
		switch {
		case ip == nil:
			log.Warnf("`%s` is not a valid IP address", host)
		case ip.To4() == nil:
			ipv6Addrs = append(ipv6Addrs, addr)
		default:
			ipv4Addrs = append(ipv4Addrs, addr)
		}
	}
	listeners := make([]net.Listener, 0, len(ipv6Addrs)+len(ipv4Addrs))
	for _, addr := range ipv4Addrs {
		listener, err := listen("tcp4", addr)
		if err != nil {
			log.Warnf("Can't listen on %s: %v", addr, err)
			continue
		}
		listeners = append(listeners, listener)
	}
	for _, addr := range ipv6Addrs {
		listener, err := listen("tcp6", addr)
		if err != nil {
			log.Warnf("Can't listen on %s: %v", addr, err)
			continue
		}
		listeners = append(listeners, listener)
	}
	return listeners
}
